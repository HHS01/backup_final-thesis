#!/usr/bin/env python3
"""
build_survey_dataset.py
=======================
Builds clean, self-contained JavaScript constants for the Community Evidence Layer:
1. SURVEY_BASELINE: Calibrated baseline distributions, quotes, and macro triangulation stats.
2. SURVEY_CODEBOOK: All 104 survey instruments questions mapped to UNESCO Six Pillars.
"""

import csv
import json
import re
from pathlib import Path
import docx

def get_docx_dict(path):
    doc = docx.Document(path)
    res = {}
    for p in doc.paragraphs:
        t = p.text.strip()
        if not t:
            continue
        m = re.match(r'^([A-G][0-9]+|[0-9]+)\.?\s+(.*)', t)
        if m:
            res[m.group(1)] = t
    return res

def main():
    root = Path('/workspaces/CC_3')
    calibrated_path = root / 'data/processed/survey_data_calibrated.json'
    codebook_path = root / 'data/AoA_Survey_to_Pillar_Codebook.csv'
    
    td = get_docx_dict(root / 'AoA survey/SSA_Teacher_Survey_v1_PUBLIC.docx')
    pd_d = get_docx_dict(root / 'AoA survey/SSA_Provider_Survey_v1_PUBLIC.docx')
    ed = get_docx_dict(root / 'AoA survey/SSA_Expert_Consultation_R1_v1_PUBLIC.docx')

    # 1. Process Baseline Data
    with open(calibrated_path, 'r', encoding='utf-8') as f:
        cal = json.load(f)

    # Keep compact version for fast client-side loading
    baseline = {
        'metadata': cal.get('metadata', {}),
        'teachers': {k: v for k, v in cal.get('teachers', {}).items() if k != 'records'},
        'providers': {k: v for k, v in cal.get('providers', {}).items() if k != 'records'},
        'experts': {k: v for k, v in cal.get('experts', {}).items() if k != 'records'},
        'triangulation': cal.get('triangulation', {})
    }

    # 2. Process Codebook (104 items)
    with open(codebook_path, 'r', encoding='utf-8') as f:
        cb_raw = list(csv.DictReader(f))

    codebook = []
    pillar_names = {
        '1': 'Management & Governance',
        '2': 'Teacher Professional Development',
        '3': 'Pedagogy & Digital Learning Materials',
        '4': 'Connectivity & Digital Infrastructure',
        '5': 'Equitable Access & Linguistic Inclusion',
        '6': 'Data Privacy & Ethics',
        'ALL': 'Cross-Pillar Systemic'
    }

    for r in cb_raw:
        qid = r['q_id']
        inst = r['instrument']
        parts = qid.split('-')
        full_text = r['question_condensed']
        if len(parts) == 2:
            lookup = td if parts[0] == 'T' else (pd_d if parts[0] == 'P' else ed)
            if parts[1] in lookup:
                full_text = lookup[parts[1]]

        p_id = r.get('pillar_primary', '').strip()
        p_name = pillar_names.get(p_id, 'Cross-Cutting / Baseline') if p_id else 'Demographics & Baseline'

        codebook.append({
            'id': qid,
            'instrument': inst,
            'question': full_text,
            'condensed': r.get('question_condensed', ''),
            'pillar_id': p_id,
            'pillar_name': p_name,
            'indicator_type': r.get('indicator_type', ''),
            'gap_flag': r.get('gap_flag', '')
        })

    out_file = root / 'data/processed/survey_evidence_data.js'
    with open(out_file, 'w', encoding='utf-8') as f:
        f.write('// Auto-generated by build_survey_dataset.py\n')
        f.write('// 1. Calibrated Baseline Synthesized Distribution (N=800: 600 Teachers, 120 Providers, 80 Experts)\n')
        f.write('const SURVEY_BASELINE = ' + json.dumps(baseline, indent=2) + ';\n\n')
        f.write('// 2. Complete 104-Item Survey Instruments Codebook mapped to UNESCO 6 Pillars\n')
        f.write('const SURVEY_CODEBOOK = ' + json.dumps(codebook, indent=2) + ';\n')

    print(f'Successfully built {out_file}:')
    print(f' - Baseline respondents: {baseline["metadata"]["summaryStats"]["totalRespondents"]}')
    print(f' - Codebook questions: {len(codebook)}')

if __name__ == '__main__':
    main()
